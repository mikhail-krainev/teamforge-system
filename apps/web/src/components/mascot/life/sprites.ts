/**
 * Sprite data for the living Yeti (see docs/design/yeti-life.md, "Interface: sprites").
 *
 * Frame conventions:
 * - Every BODY frame is a 20x20 grid, one char per cell, '.' empty. Chars come from PALETTE in
 *   ../pixels.tsx: F fur, S fur shade, B face, K ink, E eye, C cheek, plus the prop chars
 *   R red, O orange, Y yellow, W wood, P pink, U ultramarine, G green, M mint, L paper, N ink line.
 * - Frames face RIGHT; the engine mirrors them with scaleX(-1) to walk left.
 * - The head (ear tuft, face, eyes on rows 7-8) sits at the same cells as POSES.idle and the torso
 *   keeps its width, so swapping frames never jumps. Exceptions on purpose: crouch, land and sleep
 *   drop the head 1-2 rows (squash), jump lifts it 1 row (stretch), peek leans it right and down.
 * - Feet stand on row 19 in every frame; hang1/hang2 hold the cursor with both hands on row 0.
 * - PROPS offsets are the prop's top-left in body cells relative to the body's top-left and may be
 *   negative (parachute, balloon, sparkle and zzz sit above the head). fire* and logs sit to the
 *   right of the sitting body. The rag is placed by the engine at WIPE_HAND; its offset is the
 *   wipe1 spot.
 */

