// Generates MSW request handlers from the bundled OpenAPI contract.
// Usage: pnpm --filter web run mocks:generate
// Output: src/mocks/generated/handlers.ts (deterministic, committed).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const specPath = resolve(root, '../../packages/shared/openapi.json');
const outPath = resolve(root, 'src/mocks/generated/handlers.ts');
const METHODS = ['get', 'post', 'put', 'patch', 'delete'];
const MAX_DEPTH = 5;

const spec = JSON.parse(readFileSync(specPath, 'utf8'));

function resolveRef(ref) {
  return ref
    .replace(/^#\//, '')
    .split('/')
    .reduce((node, key) => node[key], spec);
}

const FORMATS = {
  uuid: '00000000-0000-4000-8000-000000000000',
  'date-time': '2026-01-01T00:00:00.000Z',
  date: '2026-01-01',
  uri: 'https://example.com/',
  email: 'user@example.com',
};

function scalar(schema, type) {
  if (type === 'integer' || type === 'number') {
    return Math.max(schema.minimum ?? 0, schema.exclusiveMinimum ?? -Infinity, 0) || 0;
  }
  if (type === 'boolean') return false;
  if (type === 'string') return FORMATS[schema.format] ?? 'string';
  return null;
}

function pickType(schema) {
  const type = Array.isArray(schema.type) ? schema.type.find((t) => t !== 'null') : schema.type;
  if (type) return type;
  if (schema.properties) return 'object';
  if (schema.items) return 'array';
  return undefined;
}

function sample(schema, seen = [], depth = 0) {
  if (!schema || depth > MAX_DEPTH) return null;
  if (schema.$ref) {
    if (seen.includes(schema.$ref)) return null;
    return sample(resolveRef(schema.$ref), [...seen, schema.$ref], depth);
  }
  if (schema.example !== undefined) return schema.example;
  if (schema.default !== undefined) return schema.default;
  if (schema.const !== undefined) return schema.const;
  if (schema.enum) return schema.enum[0];
  if (schema.allOf) {
    return Object.assign({}, ...schema.allOf.map((s) => sample(s, seen, depth + 1)));
  }
  const variant = schema.oneOf?.[0] ?? schema.anyOf?.[0];
  if (variant) return sample(variant, seen, depth + 1);
  const type = pickType(schema);
  if (type === 'array') return [sample(schema.items, seen, depth + 1)];
  if (type === 'object') {
    return Object.fromEntries(
      Object.entries(schema.properties ?? {}).map(([k, v]) => [k, sample(v, seen, depth + 1)]),
    );
  }
  return scalar(schema, type);
}

function successResponse(responses) {
  const codes = Object.keys(responses)
    .filter((c) => /^[23]\d\d$/.test(c))
    .sort();
  const code = codes[0];
  if (!code) return null;
  const resolved = responses[code].$ref ? resolveRef(responses[code].$ref) : responses[code];
  const schema = resolved.content?.['application/json']?.schema;
  return { status: Number(code), body: schema ? sample(schema) : undefined };
}

function mswPath(path) {
  return `*/api${path.replace(/\{(\w+)\}/g, ':$1')}`;
}

function renderHandler(method, path, operationId, res) {
  const init = res.status === 200 ? '' : `, { status: ${res.status} }`;
  const response =
    res.body === undefined
      ? `new HttpResponse(null, { status: ${res.status} })`
      : `HttpResponse.json(${JSON.stringify(res.body)}${init})`;
  return `  // ${operationId}\n  http.${method}(${JSON.stringify(mswPath(path))}, () => ${response}),`;
}

async function main() {
  const lines = [];
  for (const path of Object.keys(spec.paths).sort()) {
    for (const method of METHODS) {
      const op = spec.paths[path][method];
      const res = op && successResponse(op.responses ?? {});
      if (res) lines.push(renderHandler(method, path, op.operationId, res));
    }
  }
  const out = [
    '// Generated by scripts/generate-mocks.mjs from packages/shared/openapi.json. Do not edit.',
    "import { http, HttpResponse } from 'msw';",
    '',
    'export const generatedHandlers = [',
    ...lines,
    '];',
    '',
  ].join('\n');
  const options = (await resolveConfig(outPath)) ?? {};
  const formatted = await format(out, { ...options, parser: 'typescript' });
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, formatted);
  process.stdout.write(`Generated ${lines.length} MSW handlers\n`);
}

await main();
