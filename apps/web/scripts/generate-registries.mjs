// Generates the registries that pick up feature files by mask, so that parallel
// feature work never edits a shared file:
//   - src/i18n/registry.generated.ts          <- src/i18n/ru/*.json
//   - src/components/shell/nav.generated.ts   <- src/features/*/nav.ts
// Usage: node scripts/generate-registries.mjs (run by dev/build/typecheck/lint/test).
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(root, 'src');
const HEADER = '// Generated by scripts/generate-registries.mjs. Do not edit.\n';

const ident = (name) => name.replace(/[^A-Za-z0-9]/g, '_');
const list = (dir) => (existsSync(dir) ? readdirSync(dir, { withFileTypes: true }) : []);

function writeIfChanged(file, content) {
  mkdirSync(dirname(file), { recursive: true });
  const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (current !== content) writeFileSync(file, content);
}

function dictionaries() {
  const names = list(resolve(src, 'i18n/ru'))
    .filter((e) => e.isFile() && e.name.endsWith('.json'))
    .map((e) => e.name.slice(0, -'.json'.length))
    .sort();
  const imports = names.map((n) => `import ${ident(n)} from './ru/${n}.json';`);
  const entries = names.map((n) => `  ${JSON.stringify(n)}: ${ident(n)},`);
  const body = `${imports.join('\n')}\n\nexport const ruDictionaries = {\n${entries.join('\n')}\n} as const;\n`;
  writeIfChanged(resolve(src, 'i18n/registry.generated.ts'), `${HEADER}${body}`);
}

function navigation() {
  const features = list(resolve(src, 'features'))
    .filter((e) => e.isDirectory() && existsSync(resolve(src, 'features', e.name, 'nav.ts')))
    .map((e) => e.name)
    .sort();
  const imports = features.map(
    (f) => `import { navItems as ${ident(f)}Nav } from '@/features/${f}/nav';`,
  );
  const spread = features.map((f) => `  ...${ident(f)}Nav,`);
  const body = `import type { NavItem } from './nav-types';\n${imports.join('\n')}\n\nexport const allNavItems: readonly NavItem[] = [\n${spread.join('\n')}\n];\n`;
  writeIfChanged(resolve(src, 'components/shell/nav.generated.ts'), `${HEADER}${body}`);
}

dictionaries();
navigation();
