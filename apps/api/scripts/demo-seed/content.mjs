/** A link for an artifact step, picked by words of its key. */
export function artifactLink(stepKey, repoUrl, releaseUrl, salt) {
  if (/repo|code|final_links/.test(stepKey)) return repoUrl;
  if (/frontend|backend|mobile|pr_template|api/.test(stepKey)) return `${repoUrl}/pulls`;
  if (/deploy|release|smoke/.test(stepKey)) return releaseUrl;
  if (/prototype|ui|design/.test(stepKey))
    return `https://www.figma.com/file/demo${salt}/prototype`;
  if (/board/.test(stepKey)) return `${repoUrl}/projects/1`;
  if (/ci/.test(stepKey)) return `${repoUrl}/actions`;
  if (/staging/.test(stepKey)) return releaseUrl.replace('://', '://staging-');
  return `https://docs.google.com/document/d/demo-${salt}-${stepKey}`;
}

